# 1- Una tupla es una colección de elementos que se pueden
# almacenar en una sola variable. Su diferencia con
# respecto a una lista, es que sus elementos, una vez creados,
# son inmutables.
# 2- Un conjunto es una colección de elementos únicos, es decir,
# que no se repiten. Para resolver búsquedas de duplicados o
# para operar aplicando teoría de conjuntos, el set es
# preferible sobre la lista.
# 3- Un diccionario es una estructura de datos que nos permite
# almacenar los valores en forma de clave: valor. Conviene 
# usarlos por su facilidad para la búsqueda y el acceso de datos.
# 4- Combinar estructuras de datos implicaría, por ejemplo,
# crear una lista que, dentro de ella, tenga varios 
# diccionarios.